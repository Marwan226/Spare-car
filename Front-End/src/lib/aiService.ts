// AI Service for car diagnostics chatbot
// This uses a simple pattern matching system that can be easily upgraded to use real AI APIs

interface AIResponse {
  response: string;
  suggestions?: string[];
}

export async function analyzeCarProblem(
  message: string,
  imageBase64?: string
): Promise<AIResponse> {
  // Simulate API call delay
  await new Promise((resolve) => setTimeout(resolve, 1500));

  const lowerMessage = message.toLowerCase();

  // If image is provided
  if (imageBase64) {
    return {
      response: `تم تحليل الصورة والرسالة: "${message}"

بناءً على الصورة المرفوعة، يمكنني مساعدتك في:

🔍 **التشخيص الأولي:**
- فحص الجزء الظاهر في الصورة
- تحديد المشكلة المحتملة
- اقتراح الحلول المناسبة

📝 **للحصول على تشخيص دقيق:**
- صف المشكلة بالتفصيل (الأصوات، الروائح، السلوك)
- متى بدأت المشكلة؟
- هل حدث شيء قبل ظهور المشكلة؟

💡 **نصيحة:** يمكنك سؤالي عن أي شيء متعلق بالسيارات!`,
      suggestions: [
        "ما هي أسباب هذه المشكلة؟",
        "كيف أصلح هذا؟",
        "ما هي قطع الغيار المطلوبة؟",
      ],
    };
  }

  // General greeting responses
  if (
    lowerMessage.includes("مرحب") ||
    lowerMessage.includes("السلام") ||
    lowerMessage.includes("هلا") ||
    lowerMessage.includes("hello") ||
    lowerMessage.includes("hi")
  ) {
    return {
      response: `مرحباً بك! 👋

أنا مساعدك الذكي لحل مشاكل السيارات. يمكنني مساعدتك في:

🔧 **تشخيص المشاكل:**
- مشاكل المحرك والأداء
- مشاكل الفرامل والتعليق
- المشاكل الكهربائية
- مشاكل التكييف والتبريد

📸 **تحليل الصور:**
- ارفع صورة للمشكلة
- سأقوم بتحليلها وإعطائك الحل

💬 **أسئلة عامة:**
- صيانة السيارة
- نصائح القيادة
- اختيار قطع الغيار

كيف يمكنني مساعدتك اليوم؟`,
      suggestions: ["سيارتي لا تدور", "صوت غريب من المحرك", "الفرامل ضعيفة"],
    };
  }

  // Engine problems
  if (
    lowerMessage.includes("محرك") ||
    lowerMessage.includes("engine") ||
    lowerMessage.includes("تدور") ||
    lowerMessage.includes("تشتغل")
  ) {
    return {
      response: `**مشكلة في المحرك** 🔧

دعني أساعدك في تشخيص المشكلة:

**الأعراض الشائعة:**
- المحرك لا يدور؟
- صوت غريب من المحرك؟
- اهتزاز أو رجة؟
- دخان من العادم؟

**الأسباب المحتملة:**
1. 🔋 البطارية ضعيفة أو فارغة
2. ⚡ مشكلة في شمعات الإشعال
3. ⛽ نقص الوقود أو مشكلة في مضخة الوقود
4. 🛢️ نقص زيت المحرك
5. 🌡️ ارتفاع حرارة المحرك

**الحلول السريعة:**
- فحص البطارية والتوصيلات
- فحص مستوى الزيت
- فحص مستوى سائل التبريد
- فحص شمعات الإشعال

**هل تريد تفاصيل أكثر عن أي من هذه النقاط؟**`,
      suggestions: [
        "كيف أفحص البطارية؟",
        "كيف أغير شمعات الإشعال؟",
        "ما هي علامات نقص الزيت؟",
      ],
    };
  }

  // Brake problems
  if (
    lowerMessage.includes("فرامل") ||
    lowerMessage.includes("brake") ||
    lowerMessage.includes("توقف")
  ) {
    return {
      response: `**مشكلة في الفرامل** 🛑

⚠️ **تحذير:** مشاكل الفرامل خطيرة جداً! يجب الفحص فوراً.

**الأعراض:**
- صوت صرير عند الفرملة؟
- اهتزاز في دواسة الفرامل؟
- الدواسة طرية أو صلبة جداً؟
- مسافة توقف أطول من المعتاد؟

**الأسباب المحتملة:**
1. 🔴 تآكل تيل الفرامل (يحتاج تغيير كل 30,000-70,000 كم)
2. 💧 نقص سائل الفرامل
3. ⚙️ مشكلة في أقراص الفرامل
4. 🔧 مشكلة في نظام ABS

**الحلول:**
- فحص سمك تيل الفرامل (يجب أن يكون > 3mm)
- فحص مستوى سائل الفرامل
- فحص أقراص الفرامل من التشققات
- تنظيف نظام الفرامل

**متى تستبدل تيل الفرامل؟**
- صوت صرير معدني
- اهتزاز عند الفرملة
- لمبة الفرامل مضاءة

هل تحتاج مساعدة في شيء محدد؟`,
      suggestions: [
        "كيف أفحص تيل الفرامل؟",
        "ما هو سائل الفرامل المناسب؟",
        "كم تكلفة تغيير الفرامل؟",
      ],
    };
  }

  // Battery problems
  if (
    lowerMessage.includes("بطارية") ||
    lowerMessage.includes("battery") ||
    lowerMessage.includes("كهرباء")
  ) {
    return {
      response: `**مشكلة في البطارية** 🔋

**علامات ضعف البطارية:**
- صعوبة في تشغيل المحرك
- أضواء خافتة
- صوت نقر عند التشغيل
- رائحة كبريت (بيض فاسد)

**الفحص السريع:**
1. ✅ فحص الجهد: يجب أن يكون 12.6V (محرك مطفي)
2. ✅ فحص التوصيلات: نظيفة ومشدودة
3. ✅ فحص السائل: المستوى مناسب (للبطاريات القابلة للصيانة)

**عمر البطارية:**
- البطارية العادية: 3-5 سنوات
- في الجو الحار: 2-3 سنوات

**الحلول:**
- تنظيف الأطراف من الصدأ
- شحن البطارية بشاحن ذكي
- فحص المولد (الدينامو)
- استبدال البطارية إذا كان عمرها > 4 سنوات

**نصيحة:** إذا كانت البطارية جديدة والمشكلة مستمرة، قد تكون المشكلة في المولد!

ما هي الأعراض بالضبط؟`,
      suggestions: [
        "كيف أنظف أطراف البطارية؟",
        "كيف أفحص المولد؟",
        "ما هي أفضل بطارية؟",
      ],
    };
  }

  // Tire problems
  if (
    lowerMessage.includes("إطار") ||
    lowerMessage.includes("tire") ||
    lowerMessage.includes("عجل") ||
    lowerMessage.includes("كفر")
  ) {
    return {
      response: `**مشاكل الإطارات** 🚗

**الفحص الدوري:**
- ضغط الهواء: مرة شهرياً
- عمق المداس: كل 3 أشهر
- التوازن: كل 10,000 كم
- المحاذاة: عند الحاجة

**ضغط الهواء المناسب:**
- سيارات صغيرة: 30-32 PSI
- سيارات متوسطة: 32-35 PSI
- سيارات كبيرة/SUV: 35-40 PSI

**علامات التآكل:**
- تآكل من الوسط: ضغط زائد
- تآكل من الأطراف: ضغط منخفض
- تآكل من جهة واحدة: مشكلة محاذاة

**متى تستبدل الإطار؟**
- عمق المداس < 1.6mm
- تشققات في الجوانب
- انتفاخات أو فقاعات
- عمر الإطار > 6 سنوات

**نصائح الصيانة:**
- تبديل الإطارات كل 10,000 كم
- فحص الضغط عندما تكون باردة
- تجنب الوقوف على الأرصفة

ما هي مشكلتك بالتحديد؟`,
      suggestions: [
        "كيف أفحص عمق المداس؟",
        "متى أحتاج لتوازن العجلات؟",
        "ما هي علامات مشاكل المحاذاة؟",
      ],
    };
  }

  // AC problems
  if (
    lowerMessage.includes("تكييف") ||
    lowerMessage.includes("مكيف") ||
    lowerMessage.includes("ac") ||
    lowerMessage.includes("بارد")
  ) {
    return {
      response: `**مشاكل التكييف** ❄️

**الأعراض الشائعة:**
- لا يبرد نهائياً؟
- يبرد ضعيف؟
- رائحة كريهة؟
- صوت غريب؟

**الأسباب المحتملة:**
1. 🌡️ نقص غاز التبريد (الفريون)
2. 🔌 مشكلة في الكمبروسر
3. 🍃 فلتر مكيف متسخ
4. ⚡ مشكلة كهربائية (ريلاي، فيوز)
5. 🌀 مشكلة في المروحة

**الحلول:**
- تنظيف فلتر المكيف (كل 6 أشهر)
- فحص مستوى الفريون
- فحص الكمبروسر والسير
- تنظيف المكثف من الأمام

**الصيانة الدورية:**
- تشغيل المكيف 10 دقائق أسبوعياً (حتى في الشتاء)
- تنظيف الفلتر كل 6 أشهر
- فحص الفريون سنوياً

**نصيحة:** إذا كانت الرائحة كريهة، قد يكون هناك عفن في نظام التكييف!

ما هي المشكلة بالضبط؟`,
      suggestions: [
        "كيف أنظف فلتر المكيف؟",
        "كم تكلفة تعبئة الفريون؟",
        "كيف أتخلص من الرائحة؟",
      ],
    };
  }

  // Oil problems
  if (
    lowerMessage.includes("زيت") ||
    lowerMessage.includes("oil") ||
    lowerMessage.includes("تغيير")
  ) {
    return {
      response: `**زيت المحرك** 🛢️

**أهمية زيت المحرك:**
- تقليل الاحتكاك
- تبريد المحرك
- تنظيف الشوائب
- حماية من الصدأ

**متى تغير الزيت؟**
- زيت معدني: كل 5,000 كم
- زيت نصف تخليقي: كل 7,500 كم
- زيت تخليقي كامل: كل 10,000-15,000 كم

**أنواع الزيت:**
- 5W-30: للجو المعتدل
- 10W-40: للجو الحار
- 0W-20: للجو البارد

**علامات نقص الزيت:**
- لمبة الزيت مضاءة ⚠️
- صوت طقطقة من المحرك
- دخان أزرق من العادم
- رائحة احتراق

**الفحص:**
- فحص المستوى كل أسبوع
- يجب أن يكون بين MIN و MAX
- الفحص والمحرك بارد

**نصيحة مهمة:** عدم تغيير الزيت يؤدي لتلف المحرك!

هل تحتاج مساعدة في اختيار الزيت المناسب؟`,
      suggestions: [
        "ما هو الزيت المناسب لسيارتي؟",
        "كيف أفحص مستوى الزيت؟",
        "ماذا أفعل إذا كانت لمبة الزيت مضاءة؟",
      ],
    };
  }

  // Overheating
  if (
    lowerMessage.includes("حرارة") ||
    lowerMessage.includes("سخن") ||
    lowerMessage.includes("تبريد") ||
    lowerMessage.includes("overheat")
  ) {
    return {
      response: `**ارتفاع حرارة المحرك** 🌡️

⚠️ **تحذير:** لا تفتح غطاء الرديتر والمحرك ساخن!

**الأسباب:**
1. 💧 نقص سائل التبريد
2. 🔥 تلف الثرموستات
3. 🌀 عطل في مروحة التبريد
4. 🚰 انسداد الرديتر
5. 💨 تلف طرمبة الماء

**الحل الفوري:**
- أوقف السيارة فوراً
- شغل التدفئة على أقصى درجة
- انتظر حتى يبرد المحرك
- افحص مستوى سائل التبريد

**الوقاية:**
- فحص سائل التبريد شهرياً
- تغيير سائل التبريد كل سنتين
- فحص الثرموستات
- تنظيف الرديتر

**علامات التحذير:**
- مؤشر الحرارة في الأحمر
- دخان من تحت الكبوت
- رائحة حلوة (سائل التبريد)

**نسبة الخلط:**
- 50% ماء مقطر + 50% سائل تبريد

ما هي الأعراض التي تلاحظها؟`,
      suggestions: [
        "كيف أفحص سائل التبريد؟",
        "ماذا أفعل إذا ارتفعت الحرارة أثناء القيادة؟",
        "كيف أعرف أن الثرموستات تالف؟",
      ],
    };
  }

  // Maintenance questions
  if (
    lowerMessage.includes("صيانة") ||
    lowerMessage.includes("فحص") ||
    lowerMessage.includes("maintenance")
  ) {
    return {
      response: `**جدول الصيانة الدورية** 📋

**كل 1,000 كم:**
- فحص ضغط الإطارات
- فحص مستوى الزيت

**كل 5,000 كم:**
- تغيير زيت المحرك
- تغيير فلتر الزيت
- فحص الفرامل

**كل 10,000 كم:**
- تبديل الإطارات
- فحص البطارية
- فحص السيور

**كل 20,000 كم:**
- تغيير فلتر الهواء
- فحص شمعات الإشعال
- فحص نظام التعليق

**كل 40,000 كم:**
- تغيير شمعات الإشعال
- فحص نظام الوقود
- تنظيف البخاخات

**سنوياً:**
- فحص شامل
- تغيير سائل الفرامل
- فحص نظام التكييف

**نصيحة:** الصيانة الدورية توفر عليك تكاليف الإصلاحات الكبيرة!

ما هو عمر سيارتك وكم قطعت من الكيلومترات؟`,
      suggestions: [
        "ما هي الصيانة الأساسية؟",
        "كم تكلفة الصيانة الدورية؟",
        "أين أجد دليل الصيانة لسيارتي؟",
      ],
    };
  }

  // General car advice
  if (
    lowerMessage.includes("نصيحة") ||
    lowerMessage.includes("كيف") ||
    lowerMessage.includes("ماذا") ||
    lowerMessage.includes("متى")
  ) {
    return {
      response: `يسعدني مساعدتك! 😊

يمكنني الإجابة على أسئلتك حول:

**المشاكل الشائعة:**
- مشاكل المحرك والأداء
- مشاكل الفرامل
- مشاكل البطارية والكهرباء
- مشاكل الإطارات
- مشاكل التكييف
- ارتفاع الحرارة

**الصيانة:**
- جدول الصيانة الدورية
- تغيير الزيت والفلاتر
- فحص السوائل
- العناية بالإطارات

**النصائح:**
- القيادة الآمنة
- توفير الوقود
- إطالة عمر السيارة

**اسألني أي سؤال محدد** وسأجيبك بالتفصيل!

مثال: "سيارتي تصدر صوت غريب عند الفرملة"`,
      suggestions: [
        "كيف أوفر في استهلاك الوقود؟",
        "ما هي علامات تلف البطارية؟",
        "متى أحتاج لتغيير الفرامل؟",
      ],
    };
  }

  // Default response for unrecognized queries
  return {
    response: `شكراً لسؤالك! 🚗

لم أفهم سؤالك بشكل كامل. دعني أساعدك بشكل أفضل:

**يمكنك أن تسألني عن:**
- أي مشكلة في سيارتك (محرك، فرامل، بطارية، إلخ)
- الصيانة الدورية
- نصائح القيادة
- اختيار قطع الغيار

**أو يمكنك:**
- رفع صورة للمشكلة 📸
- وصف الأعراض بالتفصيل
- ذكر نوع السيارة والموديل

**أمثلة على الأسئلة:**
- "سيارتي لا تدور في الصباح"
- "صوت صرير عند الفرملة"
- "لمبة الزيت مضاءة"
- "كيف أفحص البطارية؟"

اسألني مرة أخرى بشكل أوضح! 😊`,
    suggestions: ["مشاكل المحرك", "مشاكل الفرامل", "الصيانة الدورية"],
  };
}
